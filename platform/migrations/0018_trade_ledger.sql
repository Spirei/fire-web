CREATE TABLE trade_previews (
    token_hash text PRIMARY KEY,
    owner_id text NOT NULL REFERENCES users(id),
    session_hash text NOT NULL,
    fingerprint text NOT NULL,
    record_revision bigint NOT NULL,
    cash_revision bigint NOT NULL,
    account_revision bigint NOT NULL,
    expires_at timestamptz NOT NULL DEFAULT clock_timestamp()+interval '10 minutes',
    consumed_at timestamptz
);
CREATE TABLE trade_operations (
    owner_id text NOT NULL REFERENCES users(id),
    request_id uuid NOT NULL,
    fingerprint text NOT NULL,
    result jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY(owner_id,request_id)
);
CREATE FUNCTION immutable_trade_ledger() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'actual fills require append-only corrections' USING ERRCODE='23514'; END $$;
CREATE TRIGGER immutable_trade_ledger BEFORE UPDATE OR DELETE ON trade_ledger
FOR EACH ROW EXECUTE FUNCTION immutable_trade_ledger();

CREATE FUNCTION guard_portfolio_trade_projection() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE fill trade_ledger;
BEGIN
    IF NEW.trade_tip_id IS DISTINCT FROM OLD.trade_tip_id THEN
        SELECT * INTO fill FROM trade_ledger WHERE owner_id=OLD.owner_id AND id=NEW.trade_tip_id;
        IF NOT FOUND OR fill.record_id<>OLD.id OR fill.account_id IS DISTINCT FROM OLD.broker_account_id
           OR fill.before_record_revision<>OLD.revision OR fill.previous_trade_id IS DISTINCT FROM OLD.trade_tip_id
           OR fill.before_quantity IS DISTINCT FROM OLD.qty OR fill.before_cost IS DISTINCT FROM OLD.cost
           OR fill.after_quantity IS DISTINCT FROM NEW.qty OR fill.after_cost IS DISTINCT FROM NEW.cost
           OR NEW.history_state<>'has_trades' OR NEW.deleted_at IS NOT NULL THEN
           RAISE EXCEPTION 'position projection requires its exact confirmed fill' USING ERRCODE='23514';
        END IF;
    ELSIF OLD.history_state='has_trades' AND
       (NEW.qty IS DISTINCT FROM OLD.qty OR NEW.cost IS DISTINCT FROM OLD.cost OR NEW.deleted_at IS DISTINCT FROM OLD.deleted_at) THEN
        RAISE EXCEPTION 'position with fills requires trade correction' USING ERRCODE='23514';
    END IF;
    IF (OLD.history_state='has_trades' OR NEW.trade_tip_id IS DISTINCT FROM OLD.trade_tip_id) AND
       (NEW.code<>OLD.code OR NEW.market<>OLD.market OR NEW.account_market<>OLD.account_market
       OR NEW.broker_account_id IS DISTINCT FROM OLD.broker_account_id OR NEW.source<>OLD.source) THEN
        RAISE EXCEPTION 'filled position identity is immutable' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_portfolio_trade_projection BEFORE UPDATE ON portfolio_records
FOR EACH ROW EXECUTE FUNCTION guard_portfolio_trade_projection();

CREATE FUNCTION check_trade_posting() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM cash_ledger_entries c WHERE c.id=NEW.cash_entry_id AND c.source_trade_id=NEW.id
       AND c.owner_id=NEW.owner_id AND c.account_id=NEW.account_id AND c.account_kind=NEW.account_kind
       AND c.request_id=NEW.request_id AND c.currency=NEW.settlement_currency AND c.amount=NEW.cash_delta
       AND c.kind='trade_'||NEW.side AND c.affects_owner AND c.occurred_at=NEW.occurred_at) THEN
       RAISE EXCEPTION 'fill must have its exact cash posting' USING ERRCODE='23514';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM portfolio_records r WHERE r.owner_id=NEW.owner_id AND r.id=NEW.record_id
        AND r.trade_tip_id=NEW.id AND r.qty=NEW.after_quantity AND r.cost IS NOT DISTINCT FROM NEW.after_cost
        AND r.history_state='has_trades') THEN
       RAISE EXCEPTION 'fill must update its position projection' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER check_trade_posting AFTER INSERT ON trade_ledger
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_trade_posting();
CREATE FUNCTION check_trade_cash() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.source_trade_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM trade_ledger t WHERE t.id=NEW.source_trade_id
        AND t.cash_entry_id=NEW.id AND t.owner_id=NEW.owner_id AND t.account_id=NEW.account_id
        AND t.account_kind=NEW.account_kind AND t.request_id=NEW.request_id
        AND t.settlement_currency=NEW.currency AND t.cash_delta=NEW.amount AND NEW.kind='trade_'||t.side
        AND t.occurred_at=NEW.occurred_at) THEN
        RAISE EXCEPTION 'cash posting must match the exact fill' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER check_trade_cash AFTER INSERT ON cash_ledger_entries
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_trade_cash();
