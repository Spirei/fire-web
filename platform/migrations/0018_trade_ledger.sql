-- Confirmed actual fills are internal records, never instructions to a broker.
CREATE TABLE trade_ledger (
    id uuid PRIMARY KEY,
    owner_id text NOT NULL REFERENCES users(id),
    request_id uuid NOT NULL,
    record_id text NOT NULL,
    account_id text NOT NULL,
    account_kind text NOT NULL CHECK(account_kind IN ('real','simulated')),
    side text NOT NULL CHECK(side IN ('buy','sell','dividend')),
    quantity numeric NOT NULL CHECK(quantity>=0 AND quantity<='9007199254740991'::numeric AND scale(quantity)<=18),
    price numeric NOT NULL CHECK(price>=0 AND price<='9007199254740991'::numeric AND scale(price)<=18),
    amount numeric NOT NULL CHECK(amount>=0 AND amount<='9007199254740991'::numeric AND scale(amount)<=18),
    fees numeric NOT NULL CHECK(fees>=0 AND fees<='9007199254740991'::numeric AND scale(fees)<=18),
    currency text NOT NULL CHECK(currency ~ '^[A-Z]{3}$'),
    settlement_currency text NOT NULL CHECK(settlement_currency ~ '^[A-Z]{3}$'),
    settlement_amount numeric CHECK(settlement_amount>=0 AND settlement_amount<='9007199254740991'::numeric AND scale(settlement_amount)<=18),
    cash_delta numeric NOT NULL CHECK(abs(cash_delta)<='9007199254740991'::numeric AND scale(cash_delta)<=18),
    cash_entry_id uuid NOT NULL UNIQUE,
    previous_trade_id uuid,
    before_record_revision bigint NOT NULL CHECK(before_record_revision>0),
    before_quantity numeric NOT NULL CHECK(before_quantity>=0),
    before_cost numeric,
    after_quantity numeric NOT NULL CHECK(after_quantity>=0),
    after_cost numeric,
    realized_pnl numeric,
    input_payload jsonb NOT NULL,
    source text NOT NULL DEFAULT 'owner_recorded' CHECK(source='owner_recorded'),
    occurred_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    note text NOT NULL CHECK(length(note)<=500),
    UNIQUE(owner_id,id),
    UNIQUE(owner_id,request_id),
    FOREIGN KEY(owner_id,record_id) REFERENCES portfolio_records(owner_id,id),
    FOREIGN KEY(owner_id,account_id) REFERENCES broker_accounts(owner_id,id),
    FOREIGN KEY(owner_id,previous_trade_id) REFERENCES trade_ledger(owner_id,id),
    FOREIGN KEY(cash_entry_id) REFERENCES cash_ledger_entries(id) DEFERRABLE INITIALLY DEFERRED,
    CHECK(after_quantity=CASE side WHEN 'buy' THEN before_quantity+quantity WHEN 'sell' THEN before_quantity-quantity ELSE before_quantity END),
    CHECK((currency=settlement_currency AND cash_delta=CASE WHEN side='buy' THEN -(amount+fees) ELSE amount-fees END) OR
          (currency<>settlement_currency AND settlement_amount IS NOT NULL AND cash_delta=CASE WHEN side='buy' THEN -settlement_amount ELSE settlement_amount END)),
    CHECK((side='dividend' AND quantity=0 AND price=0) OR (side<>'dividend' AND quantity>0 AND price>0 AND amount=quantity*price))
);
CREATE INDEX trade_ledger_record ON trade_ledger(owner_id,record_id,occurred_at,id);
ALTER TABLE portfolio_records ADD COLUMN trade_tip_id uuid;
ALTER TABLE portfolio_records ADD CONSTRAINT portfolio_trade_tip FOREIGN KEY(owner_id,trade_tip_id)
    REFERENCES trade_ledger(owner_id,id) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE cash_ledger_entries ADD COLUMN source_trade_id uuid;
ALTER TABLE cash_ledger_entries ADD CONSTRAINT cash_trade_source FOREIGN KEY(owner_id,source_trade_id)
    REFERENCES trade_ledger(owner_id,id) DEFERRABLE INITIALLY DEFERRED;
CREATE UNIQUE INDEX cash_one_posting_per_trade ON cash_ledger_entries(owner_id,source_trade_id)
    WHERE source_trade_id IS NOT NULL;
ALTER TABLE cash_ledger_entries DROP CONSTRAINT cash_ledger_entries_kind_check;
