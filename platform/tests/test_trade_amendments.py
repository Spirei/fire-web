from test_trading import setup,command as trade_command,submit as trade_submit

P='/api/trading/corrections'


async def case(client):
    account,record=await setup(client,name='Native manual correction')
    buy,_=await trade_submit(client,trade_command(record,quantity='10',price='10',amount='100',fees='1',occurredAt='2026-09-01T12:00:00Z'))
    sell,_=await trade_submit(client,trade_command(buy['record'],side='sell',quantity='5',price='12',amount='60',fees='0',occurredAt='2026-09-02T12:00:00Z'))
    return account,buy,sell


async def command(client,record_id,trade_id,*,price='20',fees='1'):
    response=await client.get(P,params={'recordId':record_id});assert response.status_code==200,response.text
    snapshot=response.json();item=next(row for row in snapshot['items'] if row['tradeId']==trade_id)
    return {'requestId':str(uuid4()),**{key:snapshot[key] for key in ('targetUserId','brokerAccountId','brokerRevision','snapshotRevision','recordId','recordRevision')},
      'tradeId':trade_id,'expectedAmendmentId':item['currentAmendmentId'],'action':'amend',
      'replacement':{'quantity':item['event']['quantity'],'price':price,'fees':fees,'occurredAt':item['event']['occurred_at']},
      'evidence':{'authority':'owner_recorded','kind':'owner_statement','statement':'I verified the actual original manual ledger fill, its paid fee and original cash. This changes my internal book only, not a broker instruction.',
        'actualPaidConfirmed':True,'ledgerCorrectionConfirmed':True}}


async def complete(client,data):
    proof=await client.post(P+'/preview',json=data);assert proof.status_code==200,proof.text
    done=await client.post(P+'/operations',json={'data':data,'preview':proof.json()['previewRevision']});assert done.status_code==200,done.text
    assert done.json()['state']=='completed',done.text
    return done.json(),proof.json()


@pytest.mark.asyncio
async def test_native_single_amendment_keeps_originals_and_one_effective_history_for_future_trades(client,admin,db):
    account,buy,sell=await case(client)
    async with db.connection() as conn:
        raw=await(await conn.execute('SELECT * FROM trade_ledger ORDER BY id')).fetchall()
        cash=await(await conn.execute('SELECT * FROM cash_ledger_entries ORDER BY id')).fetchall()
    data=await command(client,buy['recordId'],buy['tradeId'])
    done,proof=await complete(client,data)
    assert proof['quantityBefore']==proof['quantityAfter']=='5'
    assert Decimal(proof['costBefore'])==Decimal('8.2') and Decimal(proof['costAfter'])==Decimal('28.2')
    assert Decimal(proof['realizedBefore'])==Decimal('9.5') and Decimal(proof['realizedAfter'])==Decimal('-40.5')
    # This fixture was generated by the exact frozen old TS replay + its pure
    # accounting/decimal/portfolio functions; no old DB/config was imported.
    golden=json.loads((Path(__file__).parent/'fixtures/trade-amendment-legacy-golden.json').read_text())['vectors']
    for phase,actual_value in [('before',{'qty':proof['quantityBefore'],'cost':proof['costBefore'],'realized':proof['realizedBefore']}),('amended',{'qty':proof['quantityAfter'],'cost':proof['costAfter'],'realized':proof['realizedAfter']})]:
        assert all(abs(Decimal(str(golden[phase][key]))-Decimal(value))<Decimal('1e-10') for key,value in actual_value.items())

    assert Decimal(proof['cashEffect']['delta'])==-100 and Decimal(proof['cashEffect']['brokerAfter'])==859
    assert not done['brokerExecution'] and done['preservesOriginals']
    assert (await client.get(P+'/operations/'+data['requestId'])).json()==done
    assert (await client.post(P+'/operations',json={'data':data,'preview':proof['previewRevision']})).json()==done
    assert (await client.get('/api/trading/operations/'+buy['requestId'])).json()==buy
    assert (await client.get('/api/trading/operations/'+sell['requestId'])).json()==sell
    async with db.connection() as conn:
        assert await(await conn.execute('SELECT * FROM trade_ledger ORDER BY id')).fetchall()==raw
        assert await(await conn.execute("SELECT * FROM cash_ledger_entries WHERE kind<>'trade_correction' ORDER BY id")).fetchall()==cash
        assert (await(await conn.execute("SELECT count(*) n FROM trade_amendments")).fetchone())['n']==1
    current=(await client.get('/api/portfolio/records/'+buy['recordId'])).json()['record']
    assert current['qty']=='5' and Decimal(current['cost'])==Decimal('28.2')
    listing=await client.get('/api/trading/fills',params={'recordId':buy['recordId']});assert listing.status_code==200,listing.text
    fills={row['id']:row for row in listing.json()['items']}
    assert fills[buy['tradeId']]['price']=='20' and fills[buy['tradeId']]['cash_delta']=='-201' and fills[buy['tradeId']]['registeredCashDelta']=='-101'
    assert Decimal(fills[sell['tradeId']]['realized_pnl'])==Decimal('-40.5')
    cash_read=(await client.get('/api/cash/accounts/'+account)).json()['currencies'][0]
    assert cash_read['complete'] and Decimal(cash_read['balance'])==859,cash_read
    later,_=await trade_submit(client,trade_command(current,side='sell',quantity='4',price='20',amount='80',fees='0',occurredAt=datetime.now(UTC).isoformat()))
    assert later['record']['qty']=='1' and Decimal(later['record']['cost'])==61 and Decimal(later['cashAfter'])==939,later
    rows=(await client.get('/api/trading/fills',params={'recordId':buy['recordId']})).json()['items']
    assert sum((Decimal(row['realized_pnl']) for row in rows if row['realized_pnl'] is not None),Decimal(0))==Decimal('-40.9')
    # A second original UUID appends to the same original fill chain.
    changed=await command(client,buy['recordId'],buy['tradeId'],price='15')
    second,_=await complete(client,changed)
    assert second['amendmentId']!=done['amendmentId'] and changed['expectedAmendmentId']==done['amendmentId']
    row=(await client.get('/api/portfolio/records/'+buy['recordId'])).json()['record']
    assert row['qty']=='1' and Decimal(row['cost'])==11,row
    cash_read=(await client.get('/api/cash/accounts/'+account)).json()['currencies'][0]
    assert Decimal(cash_read['balance'])==989 and cash_read['complete']


@pytest.mark.asyncio
async def test_amendment_insufficient_actual_cash_and_causal_reorder_do_not_write(client,admin,db):
    account,buy,sell=await case(client)
