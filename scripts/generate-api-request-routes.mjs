import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const routes = [];
function walk(dir, segments) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) walk(path.join(dir, entry.name), [...segments, entry.name]);
    else if (entry.name === "route.ts" || entry.name === "route.js") routes.push(`/api/${segments.join("/")}`.replace(/\/$/, ""));
  }
}
walk(path.join(root, "app/api"), []);
routes.sort((a, b) => a.localeCompare(b, "en"));
const file = path.join(root, "lib/apiRequestRoutes.ts");
const content = `// Generated by scripts/generate-api-request-routes.mjs. Stores route templates only.\nexport const API_REQUEST_ROUTES = ${JSON.stringify(routes, null, 2)} as const;\n`;
if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) fs.writeFileSync(file, content);
